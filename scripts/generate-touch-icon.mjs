/**
 * Rasterise `frontend/public/apple-touch-icon.png` (180px) from the SAME
 * geometry as `CortexMark.tsx` and `frontend/public/favicon.svg`.
 *
 *   node scripts/generate-touch-icon.mjs
 *
 * Why this script exists. The committed touch icon was, until 2026-09-14, a
 * damaged PNG containing no mark at all - IDAT CRC failure, a broken deflate
 * stream, 179 of 180 scanlines, and white-and-blue pixels with no brand orange
 * anywhere. It had been live since the favicon work landed, because the only
 * check on it was that its URL returned 200.
 *
 * ponytail: the PNG is a committed copy of generated output, regenerated by
 *   hand rather than built in CI. Ceiling: it can go stale against favicon.svg
 *   between runs. Upgrade path: a prebuild step, if the mark ever changes often
 *   enough to be worth a CI browser download. Not tracked as an issue - the
 *   staleness is not silent, because cortex-mark-assets.test.ts decodes the
 *   committed PNG on every test run and pins its ink extent, so a stale tile
 *   fails by name. That check is the whole reason this is safe to commit; the
 *   last hand-made copy had no such check and shipped corrupt.
 */
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(ROOT, 'package.json'));
// `@playwright/test`, not `playwright-core`: the latter is not declared in any
// package.json here and resolves only because npm hoists it out of this one.
// Needs the browser binary - `npx playwright install chromium` if it is absent.
const { chromium } = require('@playwright/test');

const GROUND = '#0A091A'; // --bg-app dark, and index.html's theme-color
const SIZE = 180;
/** iOS masks and rounds the tile, so the mark is inset rather than bled out. */
const INSET = 0.72;

const faviconPath = join(ROOT, 'frontend/public/favicon.svg');
const outPath = join(ROOT, 'frontend/public/apple-touch-icon.png');

const favicon = readFileSync(faviconPath, 'utf8').replace(/<!--[\s\S]*?-->/g, '');
const viewBox = /viewBox="([^"]+)"/.exec(favicon)?.[1];
if (!viewBox) throw new Error('no viewBox in favicon.svg');
const inner = favicon.replace(/<svg[^>]*>/, '').replace('</svg>', '').trim();
if (!inner.includes('<path') || !inner.includes('<circle')) {
  throw new Error('favicon.svg carries no mark geometry - refusing to bake a blank tile');
}

const glyph = Math.round(SIZE * INSET);
const browser = await chromium.launch();
try {
  const page = await browser.newPage({
    viewport: { width: SIZE, height: SIZE },
    deviceScaleFactor: 1,
  });
  await page.setContent(
    `<body style="margin:0"><div id="tile" style="width:${SIZE}px;height:${SIZE}px;` +
      `background:${GROUND};display:flex;align-items:center;justify-content:center">` +
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${glyph}" height="${glyph}">` +
      `${inner}</svg></div></body>`,
  );
  const buf = await page.locator('#tile').screenshot();
  // Control: a screenshot that is not exactly 180x180 means deviceScaleFactor
  // did not apply, and the icon would ship at the wrong resolution.
  const [w, h] = [buf.readUInt32BE(16), buf.readUInt32BE(20)];
  if (w !== SIZE || h !== SIZE) throw new Error(`rendered ${w}x${h}, expected ${SIZE}x${SIZE}`);
  writeFileSync(outPath, buf);
  console.log(`wrote ${outPath} - ${buf.length} bytes, ${w}x${h}, viewBox "${viewBox}"`);
} finally {
  await browser.close();
}
